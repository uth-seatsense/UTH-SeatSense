-- SEAT-40: Add campus mapping and group size to the persisted schema.
-- Existing rooms intentionally remain unmapped until CS1/CS3 ownership is confirmed.
-- Booking state and one-time QR token storage follow SRS 1.9 / booking lifecycle.
BEGIN;

CREATE TABLE IF NOT EXISTS campuses (
    campus_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_campuses_code CHECK (code IN ('CS1', 'CS3'))
);

INSERT INTO campuses (code, name)
VALUES ('CS1', 'Cơ sở 1'), ('CS3', 'Cơ sở 3')
ON CONFLICT (code) DO NOTHING;

ALTER TABLE rooms
    ADD COLUMN IF NOT EXISTS campus_id INTEGER
        REFERENCES campuses(campus_id) ON DELETE RESTRICT;

COMMENT ON COLUMN rooms.campus_id IS
    'Campus mapping (CS1/CS3); NULL means legacy room has not yet been mapped.';

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS participant_count INTEGER;

ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS checkin_at TIMESTAMPTZ;
ALTER TABLE bookings
    ADD COLUMN IF NOT EXISTS no_show_at TIMESTAMPTZ;

ALTER TABLE bookings
    DROP CONSTRAINT IF EXISTS ck_bookings_participant_count;

ALTER TABLE bookings
    ADD CONSTRAINT ck_bookings_participant_count
        CHECK (participant_count IS NULL OR participant_count BETWEEN 2 AND 6);

COMMENT ON COLUMN bookings.participant_count IS
    'Group size; new booking requests require 2..6. NULL is retained only for legacy rows.';

-- Move legacy active statuses to the lifecycle used by SRS 1.9 and UC-04.
ALTER TABLE bookings
    DROP CONSTRAINT IF EXISTS bookings_status_check;
ALTER TABLE bookings
    DROP CONSTRAINT IF EXISTS ck_bookings_status;

UPDATE bookings AS booking
SET status = 'checked_in', checkin_at = checkin.checkin_time
FROM check_ins AS checkin
WHERE checkin.booking_id = booking.booking_id
  AND checkin.status = 'success'
  AND booking.status IN ('pending', 'confirmed');

UPDATE bookings
SET status = 'booked'
WHERE status IN ('pending', 'confirmed');

ALTER TABLE bookings
    ALTER COLUMN status SET DEFAULT 'booked';
ALTER TABLE bookings
    ADD CONSTRAINT ck_bookings_status
        CHECK (status IN ('booked', 'checked_in', 'completed', 'cancelled', 'no_show'));

ALTER TABLE bookings
    DROP CONSTRAINT IF EXISTS no_overlapping_bookings;
ALTER TABLE bookings
    ADD CONSTRAINT no_overlapping_bookings
    EXCLUDE USING gist (
        room_id WITH =,
        tstzrange(start_time, end_time) WITH &&
    ) WHERE (status IN ('booked', 'checked_in'));

DROP INDEX IF EXISTS idx_bookings_status;
CREATE INDEX idx_bookings_status
    ON bookings(status) WHERE status IN ('booked', 'checked_in');

COMMENT ON COLUMN bookings.checkin_at IS
    'Successful check-in time; populated while migrating existing successful check-ins.';
COMMENT ON COLUMN bookings.no_show_at IS
    'Time the scheduled no-show job transitions a booking to no_show.';

CREATE TABLE IF NOT EXISTS checkin_tokens (
    token_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_checkin_tokens_expiry CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_checkin_tokens_booking
    ON checkin_tokens(booking_id, expires_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS uq_checkin_tokens_active_booking
    ON checkin_tokens(booking_id)
    WHERE used_at IS NULL AND revoked_at IS NULL;

COMMIT;
