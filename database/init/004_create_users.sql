-- SEAT-37: User authentication table
-- Creates users table with minimal personal data and security considerations
BEGIN;

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'student' CHECK (role IN ('student', 'librarian', 'admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_users_email ON users(email);
CREATE INDEX idx_users_role ON users(role) WHERE is_active = TRUE;

COMMENT ON TABLE users IS 'User authentication and authorization. Passwords must be hashed with bcrypt/argon2.';
COMMENT ON COLUMN users.password_hash IS 'Never store plain text passwords. Use bcrypt or argon2 with appropriate work factor.';
COMMENT ON COLUMN users.email IS 'Used for authentication and contact. Must be unique.';
COMMENT ON COLUMN users.role IS 'Access control: student (basic), librarian (moderate), admin (full).';

COMMIT;
