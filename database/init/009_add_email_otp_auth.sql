-- Passwordless OTP authentication and revocable opaque access sessions.
BEGIN;

ALTER TABLE users
    ALTER COLUMN password_hash DROP NOT NULL;

COMMENT ON COLUMN users.password_hash IS
    'Legacy password field; NULL for OTP-authenticated users. Never store plaintext credentials.';

CREATE TABLE IF NOT EXISTS email_otp_challenges (
    challenge_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    otp_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts BETWEEN 0 AND 5),
    consumed_at TIMESTAMPTZ,
    CONSTRAINT ck_email_otp_expiry CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_email_otp_email_created
    ON email_otp_challenges (email, created_at DESC);

CREATE TABLE IF NOT EXISTS auth_sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    CONSTRAINT ck_auth_session_expiry CHECK (expires_at > created_at)
);

CREATE INDEX IF NOT EXISTS idx_auth_sessions_user_expiry
    ON auth_sessions (user_id, expires_at DESC);

INSERT INTO schema_migrations (version)
VALUES ('009_add_email_otp_auth') ON CONFLICT (version) DO NOTHING;

COMMIT;
