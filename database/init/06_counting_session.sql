ALTER TABLE rooms
    ADD COLUMN IF NOT EXISTS capacity_confirmed BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE IF NOT EXISTS counting_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    initial_count INTEGER NOT NULL,
    started_at TIMESTAMPTZ NOT NULL,
    ended_at TIMESTAMPTZ,
    started_by INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT ck_counting_sessions_initial_count CHECK (initial_count >= 0),
    CONSTRAINT ck_counting_sessions_end CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_counting_sessions_active_room
    ON counting_sessions (room_id) WHERE ended_at IS NULL;

INSERT INTO schema_migrations (version)
VALUES ('06_counting_session')
ON CONFLICT (version) DO NOTHING;

COMMIT;
