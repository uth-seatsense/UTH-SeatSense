-- SEAT-37: Booking system tables (Booking, CheckIn, CountEvent, AuditLog)
BEGIN;

-- Enable btree_gist extension for exclusion constraints
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- Bookings table (replaces reservations in SRS 6.1)
CREATE TABLE IF NOT EXISTS bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'confirmed', 'completed', 'cancelled')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT ck_bookings_time_order CHECK (end_time > start_time)
);

-- TC-07: Prevent overlapping bookings for the same room
-- Only active bookings (pending/confirmed) prevent overlaps
ALTER TABLE bookings
ADD CONSTRAINT no_overlapping_bookings
EXCLUDE USING gist (
    room_id WITH =,
    tstzrange(start_time, end_time) WITH &&
) WHERE (status IN ('pending', 'confirmed'));

-- Indexes for bookings
CREATE INDEX idx_bookings_room_start ON bookings(room_id, start_time);
CREATE INDEX idx_bookings_user ON bookings(user_id);
CREATE INDEX idx_bookings_status ON bookings(status) WHERE status IN ('pending', 'confirmed');

COMMENT ON TABLE bookings IS 'Room reservations. TC-07 prevents overlapping bookings on the same room.';
COMMENT ON CONSTRAINT no_overlapping_bookings ON bookings IS 'TC-07: Prevents time overlap for active bookings on the same room.';

-- CheckIn table
CREATE TABLE IF NOT EXISTS check_ins (
    checkin_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL UNIQUE REFERENCES bookings(booking_id) ON DELETE CASCADE,
    checkin_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    method VARCHAR(20) NOT NULL DEFAULT 'qr' CHECK (method IN ('qr', 'manual')),
    status VARCHAR(20) NOT NULL DEFAULT 'success' CHECK (status IN ('success', 'failed', 'expired')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX idx_checkins_booking ON check_ins(booking_id);
CREATE INDEX idx_checkins_time ON check_ins(checkin_time);

COMMENT ON TABLE check_ins IS 'Records successful check-ins for bookings. Each booking can only be checked in once.';
COMMENT ON COLUMN check_ins.method IS 'Check-in method: qr (QR code scan), manual (staff override).';

-- CountEvent table (discrete crossing events)
CREATE TABLE IF NOT EXISTS count_events (
    event_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE RESTRICT,
    direction VARCHAR(10) NOT NULL CHECK (direction IN ('in', 'out')),
    event_time TIMESTAMPTZ NOT NULL,
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    source VARCHAR(20) NOT NULL DEFAULT 'cv' CHECK (source IN ('cv', 'manual')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Unique index on event_id (already guaranteed by PRIMARY KEY, but documented)
CREATE INDEX idx_count_events_room ON count_events(room_id, event_time DESC);
CREATE INDEX idx_count_events_received ON count_events(received_at DESC);

COMMENT ON TABLE count_events IS 'Discrete entrance/exit events. Distinct from cv_count_records which are frame aggregates.';
COMMENT ON COLUMN count_events.event_id IS 'Unique event identifier. Each event is recorded exactly once.';
COMMENT ON COLUMN count_events.direction IS 'Movement direction: in (entry), out (exit).';
COMMENT ON COLUMN count_events.event_time IS 'When the event occurred (CV processing time).';
COMMENT ON COLUMN count_events.received_at IS 'When the backend received the event.';

-- AuditLog table
CREATE TABLE IF NOT EXISTS audit_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id INTEGER REFERENCES users(user_id) ON DELETE SET NULL,
    action VARCHAR(100) NOT NULL,
    entity_type VARCHAR(50),
    entity_id INTEGER,
    changes JSONB,
    ip_address VARCHAR(45),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    detail TEXT
);

CREATE INDEX idx_audit_actor_time ON audit_logs(actor_id, created_at DESC);
CREATE INDEX idx_audit_entity ON audit_logs(entity_type, entity_id, created_at DESC);
CREATE INDEX idx_audit_action ON audit_logs(action, created_at DESC);

COMMENT ON TABLE audit_logs IS 'System audit trail for security and compliance. Tracks user actions and system changes.';
COMMENT ON COLUMN audit_logs.actor_id IS 'User who performed the action. NULL for system actions.';
COMMENT ON COLUMN audit_logs.action IS 'Action performed (e.g., create_booking, cancel_booking, login, update_room).';
COMMENT ON COLUMN audit_logs.entity_type IS 'Type of entity affected (e.g., booking, room, user).';
COMMENT ON COLUMN audit_logs.entity_id IS 'ID of the affected entity.';
COMMENT ON COLUMN audit_logs.changes IS 'JSON object with old/new values for update operations.';
COMMENT ON COLUMN audit_logs.ip_address IS 'Client IP address for security tracking.';

COMMIT;
